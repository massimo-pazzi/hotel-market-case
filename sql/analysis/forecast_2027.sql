-- Прогноз загрузки, цены и дохода на номер в Петербурге на 2026–2027 гг.
-- Сценарная модель, не статистическая: годовых точек всего десять, из них два
-- ковидных года, — обучать на этом модель (регрессию, ML) бессмысленно.
--
-- Логика:
--   предложение (средний номерной фонд за год) — из заявленного ввода;
--   спрос (проданные номеро-ночи) — три сценария, откалиброванные по фактам
--     I пол. 2026 г. (IBC, Becar, Росстат);
--   загрузка = спрос / (фонд × 365);
--   цена (ADR) — сценарный рост к прошлому году;
--   доход на номер (RevPAR) = ADR × загрузка.
--
-- База — 2025 г. по данным NF Group (S1): фонд на конец года 24 902 номера
-- (таблица), средний фонд 24 314 (оценка по графику), загрузка 63,7%,
-- ADR 8 496 ₽ (таблица).
--
-- Запуск: duckdb -c ".read sql/setup.sql" -c ".read sql/analysis/forecast_2027.sql"

-- 0. Что уже известно про 2026 г.: калибровка спроса ------------------------------
-- Изменение проданных номеро-ночей в I пол. 2026 г. к I пол. 2025 г. по трём
-- независимым оценкам: (загрузка 2026 / загрузка 2025) × (фонд 2026 / фонд 2025).
SELECT * FROM (VALUES
    ('IBC / Hotel Advisors, классические отели 3–5* от 100 ном.', ROUND(((59.0 / 62) * (19.6 / 19.3) - 1) * 100, 1),
        'загрузка 62%→59% (S13), фонд 19,3→19,6 тыс. (S10)'),
    ('Becar, отели 3–5* (пресс-релиз)',                          ROUND(((61.0 / 63) * 1.02 - 1) * 100, 1),
        'загрузка 63%→61%, фонд +2% (S11)'),
    ('Росстат, размещённые лица, январь–май',                    0.0,
        'гости, а не номеро-ночи; все средства размещения (S14)')
) t(source, sold_or_guests_change_pct, basis);
-- Разброс оценок: от −3% до 0%. Базовый сценарий на 2026 г. — −1%.

-- 1. Сценарии --------------------------------------------------------------------
-- Предложение:
--   ввод 2026 — 616 номеров в гостиницах (заявлено, S1) плюс часть апарт-отелей:
--   из ~0,9 тыс. юнитов проектного объёма в фонд обычно переходит 20–25%
--   (2024: 803 из 3,2 тыс.; 2025: 491 из 2,4 тыс.), т. е. ~200 номеров.
--   Итого ~800; в «плохом» сценарии — все заявленные объекты и больше апартов
--   (1 100), в «хорошем» — переносы сроков (600).
--   ввод 2027 — в процентах от фонда: Becar ждёт 2–3% в год в 2027–2028.
-- Спрос (проданные номеро-ночи, % к прошлому году):
--   2026 — калибровка по фактам I пол. (см. выше);
--   2027 — «плохой»: охлаждение продолжается (−2%); «базовый»: стабилизация,
--   небольшой рост (+1%) — ср. прогноз Becar «турпоток на уровне 13 млн»;
--   «хороший»: возвращается половина докризисного темпа (+4%; в 2019–2025 гг.
--   спрос рос на 7,4% в год).
-- Цена (ADR, % к прошлому году):
--   «плохой» +3% (как в I пол. 2026 по Becar, ниже инфляции);
--   «базовый» +6% (прогноз IBC на 2026 г.; близко к инфляции 5,9%, по Becar);
--   «хороший» +8% (как в I пол. 2026 г. по IBC).
CREATE OR REPLACE TEMP TABLE scen AS
SELECT * FROM (VALUES
--   сценарий   ввод_2026 ввод_2027_% спрос_2026 спрос_2027 цена_2026 цена_2027
    ('плохой',   1100,     0.03,       -0.03,     -0.02,     0.03,     0.03),
    ('базовый',   800,     0.025,      -0.01,      0.01,     0.06,     0.06),
    ('хороший',   600,     0.02,        0.00,      0.04,     0.08,     0.08)
) t(scenario, intake_2026, intake_2027_pct, demand_2026, demand_2027, adr_2026, adr_2027);

CREATE OR REPLACE TEMP TABLE base_2025 AS
SELECT 24902 AS fund_end, 24314 AS fund_avg, 0.637 AS occ, 8496 AS adr;

-- 2. Расчёт --------------------------------------------------------------------------
CREATE OR REPLACE TEMP VIEW fc AS
WITH y AS (
    SELECT
        s.scenario,
        b.fund_avg * 365 * b.occ                                   AS sold_2025,
        -- средний фонд за год = на начало + половина ввода
        b.fund_end + s.intake_2026 / 2.0                           AS fund_avg_2026,
        b.fund_end + s.intake_2026                                 AS fund_end_2026,
        (b.fund_end + s.intake_2026) * (1 + s.intake_2027_pct / 2) AS fund_avg_2027,
        s.*, b.occ AS occ_2025, b.adr AS adr_2025
    FROM scen s CROSS JOIN base_2025 b
)
SELECT
    scenario,
    ROUND(fund_avg_2026)                                              AS fund_2026,
    ROUND(fund_avg_2027)                                              AS fund_2027,
    ROUND(sold_2025 * (1 + demand_2026) / (fund_avg_2026 * 365) * 100, 1) AS occ_2026,
    ROUND(sold_2025 * (1 + demand_2026) * (1 + demand_2027) / (fund_avg_2027 * 365) * 100, 1) AS occ_2027,
    ROUND(adr_2025 * (1 + adr_2026))                                  AS adr_2026,
    ROUND(adr_2025 * (1 + adr_2026) * (1 + adr_2027))                 AS adr_2027,
    occ_2025, adr_2025
FROM y;

SELECT
    scenario,
    fund_2026, fund_2027,
    occ_2026, occ_2027,
    ROUND(occ_2027 - occ_2025 * 100, 1)                         AS occ_change_2025_2027_pp,
    adr_2026, adr_2027,
    ROUND(adr_2026 * occ_2026 / 100)                            AS revpar_2026,
    ROUND(adr_2027 * occ_2027 / 100)                            AS revpar_2027,
    ROUND((adr_2026 * occ_2026 / 100 / (adr_2025 * occ_2025) - 1) * 100, 1) AS revpar_2026_pct,
    ROUND((adr_2027 * occ_2027 / (adr_2026 * occ_2026) - 1) * 100, 1)       AS revpar_2027_pct
FROM fc
ORDER BY occ_2027;

-- 3. Сравнение с чужими прогнозами на 2026 г. -----------------------------------------
-- IBC (S10, S13): загрузка −4 п. п., ADR +6%, RevPAR без изменений (своя выборка).
-- Becar (S11): загрузка во II пол. −1–2 п. п., тарифы +3–6%.
SELECT
    scenario,
    ROUND(occ_2026 - occ_2025 * 100, 1)                                       AS occ_2026_pp,
    ROUND((adr_2026 / adr_2025 - 1) * 100, 1)                                 AS adr_2026_pct,
    ROUND((adr_2026 * occ_2026 / 100 / (adr_2025 * occ_2025) - 1) * 100, 1)   AS revpar_2026_pct
FROM fc
ORDER BY occ_2026;

-- 4. Порог: какой рост цены в 2027 г. нужен, чтобы доход на номер не упал,
--    при загрузке базового сценария? (обратная задача)
SELECT
    ROUND(occ_2026, 1) AS occ_2026,
    ROUND(occ_2027, 1) AS occ_2027,
    ROUND((occ_2026 / occ_2027 - 1) * 100, 1) AS adr_growth_needed_pct
FROM fc
WHERE scenario = 'базовый';

-- 5. Где в году пустые номера (2025 г., помесячная загрузка NF Group, S1) --------------
-- Если спросу и есть куда расти, то в месяцы с низкой загрузкой: летом отели
-- почти полны. Доля непроданных номеро-ночей по сезонам (фонд постоянный).
SELECT
    CASE WHEN month IN (11, 12, 1, 2, 3) THEN 'ноябрь–март'
         WHEN month IN (6, 7, 8)         THEN 'июнь–август'
         ELSE 'апрель–май, сентябрь–октябрь' END              AS season,
    ROUND(AVG(occupancy_label))                                AS avg_occ_pct,
    ROUND(SUM(DAY(LAST_DAY(MAKE_DATE(2025, month, 1))) * (100 - occupancy_label))
        / SUM(SUM(DAY(LAST_DAY(MAKE_DATE(2025, month, 1))) * (100 - occupancy_label))) OVER () * 100) AS share_of_empty_rooms_pct
FROM monthly_chart
WHERE year = 2025
GROUP BY season
ORDER BY avg_occ_pct;

-- 6. Чувствительность: на сколько пунктов меняется загрузка 2027 г. при изменении
--    спроса или ввода на 1% (базовый сценарий)
SELECT
    ROUND(occ_2027 * 0.01, 2) AS occ_pp_per_1pct_demand_or_supply
FROM fc WHERE scenario = 'базовый';

-- 7. Стресс-сценарий 2027 г.: налоги, топливо, корпоративные бюджеты ------------------
-- Каждый фактор — отдельной строкой, чтобы было видно, откуда берётся итог.
-- Источники и допущения:
--   [F1] Автотуризм: 2,8 млн автопоездок, 24% внутреннего турпотока (NF Group, S1, с. 6).
--   [F2] Внутренний турпоток — 94% всего (11,6 из 12,4 млн, S1, с. 6).
--   [F3] Допущение: из-за перебоев и цен на топливо автопоездок на 10% меньше;
--        30% отказавшихся едут поездом, остальные не едут.
--   [B1] Деловые туристы — ~11% турпотока (1,4 из 12,5 млн, Комитет по туризму в
--        пересказе СМИ; на gov.spb.ru цифра не найдена — НЕ СВЕРЕНО).
--   [B2] Допущение: корпоративные поездки −10% из-за налогового давления на бизнес
--        (для сравнения: по России деловых поездок в 2025 г. −8%, Forbes — не сверено).
--   [T1] Туристический налог СПб (закон 738-158, nalog.gov.ru): 2026 — 1% (окт–март)
--        и 2% (апр–сен); 2027 — 1,5% и 3%. В стресс-сценарии отели не могут
--        переложить прирост налога на гостей и платят его из выручки.
-- Упрощение: доля фактора в турпотоке = его доля в проданных номеро-ночах.
-- Деловые гости, скорее всего, чаще живут в отелях, чем в среднем, — тогда
-- эффект [B2] больше; ниже есть вариант с долей 20%.
CREATE OR REPLACE TEMP TABLE stress AS
SELECT
    0.24 * 0.94 * 0.10 * (1 - 0.30)  AS auto_loss,      -- доля потока, которая не приедет
    0.11 * 0.10                      AS corp_loss,
    0.20 * 0.10                      AS corp_loss_high;

-- Средняя прибавка турналога в 2027 г., взвешенная по выручке месяцев 2025 г.
CREATE OR REPLACE TEMP VIEW tax_add AS
SELECT
    SUM(adr_est * occupancy_label * DAY(LAST_DAY(MAKE_DATE(2025, month, 1)))
        * CASE WHEN month BETWEEN 4 AND 9 THEN 0.01 ELSE 0.005 END)
  / SUM(adr_est * occupancy_label * DAY(LAST_DAY(MAKE_DATE(2025, month, 1))))  AS tax_increment
FROM monthly_chart WHERE year = 2025;

SELECT
    ROUND(auto_loss * 100, 2)        AS auto_loss_pct,
    ROUND(corp_loss * 100, 2)        AS corp_loss_pct,
    ROUND(corp_loss_high * 100, 2)   AS corp_loss_if_20pct_share,
    ROUND((SELECT tax_increment FROM tax_add) * 100, 2) AS tourist_tax_increment_pct
FROM stress;

-- Стресс = базовый сценарий (фонд, спрос 2026, цена) + потери спроса 2027 + налог
WITH b AS (
    SELECT f.*, s.demand_2027, s.adr_2027 AS adr_growth_2027
    FROM fc f JOIN scen s USING (scenario)
    WHERE scenario = 'базовый'
), v AS (
    SELECT 'базовый'                  AS variant, 0.0 AS extra_loss, 0.0 AS tax FROM stress
    UNION ALL
    SELECT 'стресс: топливо',          auto_loss, 0.0 FROM stress
    UNION ALL
    SELECT 'стресс: топливо + бизнес', auto_loss + corp_loss, 0.0 FROM stress
    UNION ALL
    SELECT 'стресс: всё + налог',      auto_loss + corp_loss, (SELECT tax_increment FROM tax_add) FROM stress
    UNION ALL
    SELECT 'стресс: всё + налог, доля бизнеса 20%', auto_loss + corp_loss_high, (SELECT tax_increment FROM tax_add) FROM stress
)
SELECT
    v.variant,
    ROUND(((1 + b.demand_2027) * (1 - v.extra_loss) - 1) * 100, 1)             AS demand_2027_pct,
    ROUND(b.occ_2027 * (1 - v.extra_loss), 1)                                    AS occ_2027,
    -- чистая цена для отеля: базовый рост минус прирост налога, который он платит сам
    ROUND(b.adr_2026 * (1 + b.adr_growth_2027 - v.tax))                           AS net_adr_2027,
    ROUND((b.adr_2026 * (1 + b.adr_growth_2027 - v.tax) * b.occ_2027 * (1 - v.extra_loss)
           / (b.adr_2026 * b.occ_2026) - 1) * 100, 1)                             AS revpar_2027_pct
FROM b CROSS JOIN v
ORDER BY revpar_2027_pct DESC;
